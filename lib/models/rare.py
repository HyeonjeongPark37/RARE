            depth_conf     = (1. / (depth_net_out_conf[:, 0:1].sigmoid() + 1e-6) - 1.) + depth_geo_conf.unsqueeze(-1)     

            
            res['train_tag'] = torch.ones(o_num_mask_bin*self.num_hypo).type(torch.bool).to(device_id)
