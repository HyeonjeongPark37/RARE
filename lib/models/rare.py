            res['offset_3d'] = self.offset_3d(roi_features_final)#[:,:,0,0]
            res['size_3d']= size3d_offset
            res['h3d_log_variance'] = h3d_log_std
            res['iou_conf'] = iou_conf

            res['indices_conf'] = inds_filled.unsqueeze(-1).expand(BATCH_SIZE, self.num_queries, self.num_hypo).reshape(BATCH_SIZE, -1)  # [B, Q*H]
            res['cls_ids_conf'] = cls_ids_filled.unsqueeze(-1).expand(BATCH_SIZE, self.num_queries, self.num_hypo).reshape(BATCH_SIZE, -1)  # [B, Q*H]
            res['bb_3d_logit'] = bb_3d_logit

